from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class MemeScene:
    keyword: str
    good: str
    avoid: str
    message: str
    item: str
    event: str
    mood: str


def _scenes(content: str) -> tuple[MemeScene, ...]:
    return tuple(MemeScene(*line.strip().split("|")) for line in content.strip().splitlines())


def _titles(content: str) -> tuple[tuple[str, ...], ...]:
    return tuple(tuple(line.strip().split("|")) for line in content.strip().splitlines())


